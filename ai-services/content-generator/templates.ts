/**
 * Get template for specific platform and content type
 */
export function getTemplate(platform: string, type: string): string {
  const platformTemplates = TEMPLATES[platform.toLowerCase()];
  if (!platformTemplates) {
    return 'قالب غير متاح لهذه المنصة، يرجى استخدام قالب عام.';
  }

  const template = platformTemplates[type as keyof PlatformTemplate];
  if (!template) {
    return 'قالب غير متاح لهذا النوع من المحتوى، يرجى استخدام قالب عام.';
  }

  return template;
}

